package com.example.orders.payment.domain;

/** Состояния платежа. Допустимые значения закреплены ограничением {@code CHECK} в {@code payments.status}. */
public enum PaymentStatus {

    /**
     * Платёж авторизован. Имитатор не моделирует отдельный этап подтверждения списания.
     */
    AUTHORIZED,

    /** Платёж отклонён. Новая попытка требует нового заказа. */
    FAILED,

    /** Авторизованный платёж возвращён после отмены заказа. */
    REFUNDED
}
